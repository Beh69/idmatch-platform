// ---------------------------------------------------------------------------
// Downloadable document drafts for the ID05 acceptance flow. Each draft is a
// printable HTML document pre-filled with the project/offer details, with blank
// fields (________) for the customer to complete. The customer downloads the
// draft, fills it in, then uploads a photo/scan of the completed document in the
// supporting-documents step.
// ---------------------------------------------------------------------------

export interface DraftContext {
  offerId: string;
  idpId: string;
  amountSgd: number;
  customerName: string;
  designerName: string;
}

const sgd = (n: number) => "S$" + n.toLocaleString("en-SG", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const today = () => new Date().toLocaleDateString("en-SG", { day: "2-digit", month: "long", year: "numeric" });

function wrap(title: string, bodyHtml: string): string {
  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><title>${title}</title>
<style>
  body { font-family: Georgia, "Times New Roman", serif; color:#111; max-width:800px; margin:40px auto; padding:0 32px; line-height:1.6; }
  h1 { font-size:20px; border-bottom:2px solid #11204a; padding-bottom:8px; color:#11204a; }
  h2 { font-size:15px; margin-top:24px; color:#11204a; }
  .meta { color:#555; font-size:13px; }
  .fill { display:inline-block; min-width:180px; border-bottom:1px solid #333; }
  .row { margin:10px 0; }
  table { width:100%; border-collapse:collapse; margin:12px 0; }
  td, th { border:1px solid #bbb; padding:7px 10px; text-align:left; font-size:14px; }
  .sign { margin-top:40px; display:flex; justify-content:space-between; }
  .sign div { width:45%; }
  .line { border-top:1px solid #333; margin-top:40px; padding-top:4px; font-size:13px; }
  .note { background:#f4f6fb; border-left:4px solid #6c8cff; padding:10px 14px; font-size:13px; margin:16px 0; }
  @media print { body { margin:0; } }
</style></head><body>
<div class="note">This is a DRAFT for completion. Fill in the blank fields (________), then save/print it (Ctrl/Cmd+P → Save as PDF) and upload an image of the completed document in the platform.</div>
${bodyHtml}
<p class="meta" style="margin-top:40px">Generated by IDMatch · ${today()} · Reference ${title.replace(/\s+/g, "-").toUpperCase()}-${Math.random().toString(36).slice(2, 8).toUpperCase()}</p>
</body></html>`;
}

